"""Persistent media on Cloudinary for hosts without a lasting disk (Render's free tier).

Enabled only when CLOUDINARY_URL (cloudinary://<key>:<secret>@<cloud name>) is set; otherwise the
project keeps using MEDIA_ROOT / PRIVATE_MEDIA_ROOT on the local disk.

* PublicCloudinaryStorage: processed, EXIF-stripped item photos. Delivered by Cloudinary's CDN
  under the same random names as before (items/2026/10/<uuid>.jpg), so existing database paths
  keep working.
* PrivateCloudinaryStorage: claim attachments, handover proof, signatures, disposal evidence.
  Stored with Cloudinary's "authenticated" delivery type: the files cannot be fetched without a
  signed URL. The signed URL is generated and used only on the server inside the permission-
  checked view (lostfound.views.security.private_file); it is never sent to a browser, and
  url() refuses to build a public address.

File names are kept exactly; images are not stored in PostgreSQL.
"""
import posixpath
import urllib.error
import urllib.request

from django.conf import settings
from django.core.files.base import ContentFile
from django.core.files.storage import Storage
from django.utils.deconstruct import deconstructible


def cloudinary_enabled():
    return bool(getattr(settings, "CLOUDINARY_URL", ""))


def _cloudinary():
    import cloudinary
    import cloudinary.api
    import cloudinary.uploader
    import cloudinary.utils
    from urllib.parse import unquote, urlparse
    raw = settings.CLOUDINARY_URL.strip()
    if raw.startswith("CLOUDINARY_URL="):  # the dashboard copies "CLOUDINARY_URL=cloudinary://..."
        raw = raw.split("=", 1)[1]
    parts = urlparse(raw)
    if parts.scheme != "cloudinary" or not (parts.hostname and parts.username and parts.password):
        raise ValueError("CLOUDINARY_URL must look like cloudinary://<api key>:<api secret>@<cloud name>.")
    cloudinary.config(cloud_name=parts.hostname, api_key=unquote(parts.username),
                      api_secret=unquote(parts.password), secure=True)
    return cloudinary


def _split(name):
    """items/2026/10/abc.jpg -> ("items/2026/10/abc", "jpg")"""
    name = name.replace("\\", "/").lstrip("/")
    root, ext = posixpath.splitext(name)
    return root, ext.lstrip(".").lower() or None


@deconstructible
class _CloudinaryStorage(Storage):
    delivery_type = "upload"

    # -- writing -------------------------------------------------------------------------
    def _save(self, name, content):
        cld = _cloudinary()
        public_id, fmt = _split(name)
        if hasattr(content, "seek"):
            content.seek(0)
        cld.uploader.upload(content, public_id=public_id, resource_type="image", type=self.delivery_type,
                            overwrite=False, unique_filename=False, use_filename=False, invalidate=False)
        return name.replace("\\", "/")

    def get_available_name(self, name, max_length=None):
        # Names are random UUIDs generated by lostfound.services.images, so a clash is not a
        # practical concern; skipping the per-save existence lookup avoids Admin API rate limits.
        return name.replace("\\", "/")

    def delete(self, name):
        public_id, _ = _split(name)
        _cloudinary().uploader.destroy(public_id, resource_type="image", type=self.delivery_type, invalidate=True)

    # -- reading -------------------------------------------------------------------------
    def _resource(self, name):
        cld = _cloudinary()
        public_id, _ = _split(name)
        try:
            return cld.api.resource(public_id, resource_type="image", type=self.delivery_type)
        except cld.exceptions.NotFound:
            return None

    def exists(self, name):
        return self._resource(name) is not None

    def size(self, name):
        res = self._resource(name)
        if res is None:
            raise FileNotFoundError(name)
        return res.get("bytes", 0)

    def _delivery_url(self, name):
        cld = _cloudinary()
        public_id, fmt = _split(name)
        url, _ = cld.utils.cloudinary_url(public_id, resource_type="image", type=self.delivery_type, format=fmt,
                                          secure=True, sign_url=self.delivery_type != "upload")
        return url

    def _open(self, name, mode="rb"):
        if "w" in mode or "a" in mode:
            raise ValueError("Cloud media is written with save(), not opened for writing.")
        try:
            with urllib.request.urlopen(self._delivery_url(name), timeout=getattr(settings, "MEDIA_FETCH_TIMEOUT", 15)) as r:
                data = r.read()
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                raise FileNotFoundError(name) from None
            raise
        f = ContentFile(data, name=posixpath.basename(name))
        return f


@deconstructible
class PublicCloudinaryStorage(_CloudinaryStorage):
    delivery_type = "upload"

    def url(self, name):
        return self._delivery_url(name)


@deconstructible
class PrivateCloudinaryStorage(_CloudinaryStorage):
    delivery_type = "authenticated"

    def url(self, name):
        raise ValueError("Private files have no public URL.")
